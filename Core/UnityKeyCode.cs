public static class KeyCodeHelper
{

    public static int ToVk(this KeyCode k) => k switch
    {
        KeyCode.Backspace => 0x08,
        KeyCode.Tab => 0x09,
        KeyCode.Return => 0x0D,
        KeyCode.Pause => 0x13,
        KeyCode.Escape => 0x1B,
        KeyCode.Space => 0x20,
        KeyCode.PageUp => 0x21,
        KeyCode.PageDown => 0x22,
        KeyCode.End => 0x23,
        KeyCode.Home => 0x24,
        KeyCode.LeftArrow => 0x25,
        KeyCode.UpArrow => 0x26,
        KeyCode.RightArrow => 0x27,
        KeyCode.DownArrow => 0x28,
        KeyCode.Comma => 0xBC,
        KeyCode.Minus => 0xBD,
        KeyCode.Period => 0xBE,
        KeyCode.Slash => 0xBF,
        KeyCode.Semicolon => 0xBA,
        KeyCode.Equals => 0xBB,
        KeyCode.LeftBracket => 0xDB,
        KeyCode.Backslash => 0xDC,
        KeyCode.RightBracket => 0xDD,
        KeyCode.BackQuote => 0xC0,
        KeyCode.Numlock => 0x90,
        KeyCode.CapsLock => 0x14,
        KeyCode.ScrollLock => 0x91,
        KeyCode.RightShift => 0xA1,
        KeyCode.LeftShift => 0xA0,
        KeyCode.RightControl => 0xA3,
        KeyCode.LeftControl => 0xA2,
        KeyCode.RightAlt => 0xA5,
        KeyCode.LeftAlt => 0xA4,
        KeyCode.LeftMeta => 0x5B,
        KeyCode.RightMeta => 0x5C,
        KeyCode.Print => 0x2C,
        KeyCode.SysReq => 0x44,
        KeyCode.Menu => 0x5D,
        KeyCode.Insert => 0x2D,
        KeyCode.Delete => 0x2E,
        KeyCode.Quote => 0xDE,
        _ when k >= KeyCode.Keypad0 && k <= KeyCode.Keypad9 => 0x60 + (k - KeyCode.Keypad0),
        KeyCode.KeypadPeriod => 0x6E,
        KeyCode.KeypadDivide => 0x6F,
        KeyCode.KeypadMultiply => 0x6A,
        KeyCode.KeypadMinus => 0x6D,
        KeyCode.KeypadPlus => 0x6B,
        _ when k >= KeyCode.Alpha0 && k <= KeyCode.Alpha9 => 0x30 + (k - KeyCode.Alpha0),
        _ when k >= KeyCode.A && k <= KeyCode.Z => (int)k - 32,
        _ when k >= KeyCode.F1 && k <= KeyCode.F24 => 0x70 + (k - KeyCode.F1),
        _ => 0,
    };


    public static KeyCode FromVk(int vk) => vk switch
    {
        0x08 => KeyCode.Backspace,
        0x09 => KeyCode.Tab,
        0x0D => KeyCode.Return,
        0x13 => KeyCode.Pause,
        0x1B => KeyCode.Escape,
        0x20 => KeyCode.Space,
        0x21 => KeyCode.PageUp,
        0x22 => KeyCode.PageDown,
        0x23 => KeyCode.End,
        0x24 => KeyCode.Home,
        0x25 => KeyCode.LeftArrow,
        0x26 => KeyCode.UpArrow,
        0x27 => KeyCode.RightArrow,
        0x28 => KeyCode.DownArrow,
        0xBC => KeyCode.Comma,
        0xBD => KeyCode.Minus,
        0xBE => KeyCode.Period,
        0xBF => KeyCode.Slash,
        0xBA => KeyCode.Semicolon,
        0xBB => KeyCode.Equals,
        0xDB => KeyCode.LeftBracket,
        0xDC => KeyCode.Backslash,
        0xDD => KeyCode.RightBracket,
        0xC0 => KeyCode.BackQuote,
        0x90 => KeyCode.Numlock,
        0x14 => KeyCode.CapsLock,
        0x91 => KeyCode.ScrollLock,
        0xA1 => KeyCode.RightShift,
        0xA0 => KeyCode.LeftShift,
        0xA3 => KeyCode.RightControl,
        0xA2 => KeyCode.LeftControl,
        0xA5 => KeyCode.RightAlt,
        0xA4 => KeyCode.LeftAlt,
        0x5B => KeyCode.LeftMeta,
        0x5C => KeyCode.RightMeta,
        0x2C => KeyCode.Print,
        0x5D => KeyCode.Menu,
        0x2D => KeyCode.Insert,
        0x2E => KeyCode.Delete,
        0xDE => KeyCode.Quote,
        _ when vk >= 0x60 && vk <= 0x69 => KeyCode.Keypad0 + (vk - 0x60),
        0x6E => KeyCode.KeypadPeriod,
        0x6F => KeyCode.KeypadDivide,
        0x6A => KeyCode.KeypadMultiply,
        0x6D => KeyCode.KeypadMinus,
        0x6B => KeyCode.KeypadPlus,
        _ when vk >= 0x30 && vk <= 0x39 => KeyCode.Alpha0 + (vk - 0x30),
        _ when vk >= 0x41 && vk <= 0x5A => KeyCode.A + (vk - 0x41),
        _ when vk >= 0x70 && vk <= 0x87 => KeyCode.F1 + (vk - 0x70),
        _ => KeyCode.None,
    };


    public static string ToLabel(this KeyCode k) => k switch
    {
        KeyCode.Backspace => "BS",
        KeyCode.Tab => "Tab",
        KeyCode.Return => "Ent",
        KeyCode.Escape => "Esc",
        KeyCode.Space => "Spc",
        KeyCode.LeftShift => "LS",
        KeyCode.RightShift => "RS",
        KeyCode.LeftControl => "LC",
        KeyCode.RightControl => "RC",
        KeyCode.CapsLock => "Cap",
        KeyCode.Equals => "=",
        KeyCode.Minus => "-",
        KeyCode.Comma => ",",
        KeyCode.Period => ".",
        KeyCode.Semicolon => ";",
        KeyCode.Slash => "/",
        KeyCode.LeftBracket => "[",
        KeyCode.RightBracket => "]",
        KeyCode.Backslash => @"\",

        KeyCode.BackQuote => "`",
        KeyCode.Print => "PrtSc",
        KeyCode.SysReq => "SysRq",
        KeyCode.ScrollLock => "ScrLk",
        KeyCode.Pause => "Pause",
        KeyCode.Insert => "Ins",
        KeyCode.Delete => "Del",
        KeyCode.Home => "Home",
        KeyCode.End => "End",
        KeyCode.PageUp => "PgUp",
        KeyCode.PageDown => "PgDn",
        KeyCode.LeftArrow => "←",
        KeyCode.UpArrow => "↑",
        KeyCode.RightArrow => "→",
        KeyCode.DownArrow => "↓",
        KeyCode.LeftMeta => "Win",
        KeyCode.RightMeta => "Win",
        KeyCode.Menu => "Menu",
        KeyCode.Quote => "'",
        KeyCode.Numlock => "Num",
        KeyCode.Alpha0 => "0", KeyCode.Alpha1 => "1", KeyCode.Alpha2 => "2",
        KeyCode.Alpha3 => "3", KeyCode.Alpha4 => "4", KeyCode.Alpha5 => "5",
        KeyCode.Alpha6 => "6", KeyCode.Alpha7 => "7", KeyCode.Alpha8 => "8",
        KeyCode.Alpha9 => "9",
        _ when k >= KeyCode.Keypad0 && k <= KeyCode.Keypad9 => ((int)k - (int)KeyCode.Keypad0).ToString(),
        KeyCode.KeypadPeriod => ".",
        KeyCode.KeypadDivide => "/",
        KeyCode.KeypadMultiply => "*",
        KeyCode.KeypadMinus => "-",
        KeyCode.KeypadPlus => "+",
        _ when k >= KeyCode.A && k <= KeyCode.Z => k.ToString(),
        _ when k >= KeyCode.F1 && k <= KeyCode.F24 => $"F{(int)k - (int)KeyCode.F1 + 1}",
        _ => k.ToString(),
    };


    public static string ToFullLabel(this KeyCode k) => ToLabel(k) switch
    {
        "Cap" => "Caps",
        "LS" => "LShift",
        "RS" => "RShift",
        "Ent" => "Enter",
        "Spc" => "\u2423",
        "LeftAlt" => "LAlt",
        "RightAlt" => "RAlt",
        var s => s,
    };
}
